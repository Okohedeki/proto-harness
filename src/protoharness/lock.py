"""Looks up every part at the configured sources and records the results in parts.lock.json.

device.yaml holds intent (which part); the lock holds market facts (stock, price, lifecycle)
with the source and time they were seen. Re-run `ph parts` to refresh it.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Callable

from .model import LOCK_FILE, Device
from .sources import SOURCES, Offer, SourceError


def lookup_part(part: dict[str, Any], sources: list[str],
                fetchers: dict[str, Callable[[dict[str, Any]], list[Offer]]] | None = None) -> dict[str, Any]:
    fetchers = fetchers or SOURCES
    offers: list[Offer] = []
    errors: dict[str, str] = {}
    for name in sources:
        try:
            offers.extend(fetchers[name](part))
        except SourceError as exc:
            errors[name] = str(exc)
    return {
        "mpn": part.get("mpn"),
        "looked_up": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sources": [s for s in sources if s not in errors],
        "offers": [o.to_json() for o in offers],
        "errors": errors,
    }


def needs_lookup(part: dict[str, Any]) -> bool:
    mpn = str(part.get("mpn") or "").strip()
    return bool(mpn) and mpn.upper() != "TBD" and not part.get("no_lookup")


def update_lock(device: Device, sources: list[str], only: list[str] | None = None,
                fetchers=None, progress: Callable[[str, dict[str, Any]], None] | None = None) -> dict[str, Any]:
    lock = dict(device.lock) if device.lock else {}
    entries = dict(lock.get("parts") or {})
    for part in device.parts:
        pid = part.get("id")
        if only and pid not in only:
            continue
        if not needs_lookup(part):
            continue
        entries[pid] = lookup_part(part, sources, fetchers)
        if progress:
            progress(pid, entries[pid])
    known = {p.get("id") for p in device.parts}
    lock = {"note": "Generated by `ph parts`. Live distributor data; do not edit by hand.",
            "parts": {k: v for k, v in sorted(entries.items()) if k in known}}
    device._lock = lock
    return lock


def write_lock(device: Device, lock: dict[str, Any]) -> None:
    (device.root / LOCK_FILE).write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
